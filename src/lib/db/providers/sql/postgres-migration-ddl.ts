/**
 * PostgreSQL is the shape the shared building blocks were written from, so every statement is the shared one and
 * the migration is wrapped in `BEGIN;` and `COMMIT;`.
 */
import {
  autoNumberedColumnDef,
  BEGIN_COMMIT,
  defaultSql,
  standardAddColumn,
  standardAddForeignKey,
  standardColumnDef,
  standardCreateIndex,
  standardCreateTableForeignKey,
  standardDropColumn,
  standardDropForeignKey,
  standardDropIndex,
  standardDropTable,
  standardModifyColumn,
  standardPrimaryKey,
} from "@/lib/db/migration-ddl/shared";
import type { ColumnDiff, MigrationDdlSpec, TableDdlWritten } from "@/lib/db/migration-ddl/types";

const IDENTITY_COLUMN_DEF = autoNumberedColumnDef("GENERATED BY DEFAULT AS IDENTITY");

/** A default that is one sequence call and nothing else, the way `pg_get_expr` prints a serial's. */
const SEQUENCE_DEFAULT = /^nextval\('((?:[^']|'')+)'::regclass\)$/i;

/** One name as PostgreSQL prints a regclass: bare, or double-quoted with `""` for a quote, and schema-qualified at most once. */
const NAME_PART = String.raw`(?:"(?:[^"]|"")+"|[A-Za-z_][A-Za-z0-9_$]*)`;
const SEQUENCE_NAME = new RegExp(`^${NAME_PART}(?:\\.${NAME_PART})?$`);

/**
 * The sequence a column's default draws from, as the regclass text PostgreSQL printed (already a valid, quoted name),
 * or `undefined` for any other default, and for a text that is not a name, so a stored snapshot cannot put a
 * statement of its own into the migration through it.
 */
function sequenceOf(col: ColumnDiff): string | undefined {
  const match = SEQUENCE_DEFAULT.exec((defaultSql(col) ?? "").trim());
  const name = match?.[1].replaceAll("''", "'");
  return name !== undefined && SEQUENCE_NAME.test(name) ? name : undefined;
}

const SEQUENCE_TYPES: ReadonlySet<string> = new Set(["smallint", "integer", "bigint"]);
const WHOLE_NUMBER = /^-?\d+$/;

/**
 * The options of the sequence a column's default draws from, as `CREATE SEQUENCE` takes them after the name, or ""
 * where the provider read none. Every one is written, so the sequence is the one that was read rather than one whose
 * options fall back to their defaults: measured on PostgreSQL 19.0, a sequence declared `START 1000 INCREMENT 5` was
 * recreated as `CREATE SEQUENCE name;` and the rebuilt table numbered its rows 1, 2, 3. A type that is not a sequence
 * type or a bound that is not a whole number writes "", so a stored snapshot cannot put a statement of its own here.
 */
function sequenceOptions(col: ColumnDiff): string {
  const s = col.targetSequence;
  if (s === undefined || !SEQUENCE_TYPES.has(s.dataType)) return "";
  if (![s.start, s.increment, s.min, s.max, s.cache].every((n) => WHOLE_NUMBER.test(n))) return "";
  const cycle = s.cycle ? "CYCLE" : "NO CYCLE";
  return ` AS ${s.dataType} INCREMENT BY ${s.increment} MINVALUE ${s.min} MAXVALUE ${s.max} START WITH ${s.start} CACHE ${s.cache} ${cycle}`;
}

/**
 * A computed column (R9): its expression, which PostgreSQL keeps where it keeps a default, is written as the
 * generation expression. Measured on PostgreSQL 19.0, `DEFAULT (a * 3)` is `cannot use column reference in DEFAULT
 * expression`. VIRTUAL is PostgreSQL 18's and later, which is where a column read as virtual came from.
 */
const columnDef: TableDdlWritten["columnDef"] = (col, column) => {
  const expression = defaultSql(col);
  if (col.targetGenerated !== undefined && expression !== undefined) {
    const type = col.targetType || col.sourceType || "TEXT";
    const nullable = col.targetNullable === false ? " NOT NULL" : "";
    return `${column} ${type} GENERATED ALWAYS AS (${expression}) ${col.targetGenerated.toUpperCase()}${nullable}`;
  }
  // An identity column as one (R8); a column a sequence feeds keeps its `nextval(...)` default instead.
  return expression === undefined ? IDENTITY_COLUMN_DEF(col, column) : standardColumnDef(col, column);
};

export const POSTGRES_MIGRATION_DDL: MigrationDdlSpec = {
  tableDdl: "written",
  transactionWrapper: BEGIN_COMMIT,
  createTable: { kind: "written", primaryKey: standardPrimaryKey, foreignKey: standardCreateTableForeignKey },
  columnDef,
  createIndex: standardCreateIndex,
  dropIndex: standardDropIndex,
  addForeignKey: standardAddForeignKey,
  dropForeignKey: standardDropForeignKey,
  addColumn: standardAddColumn,
  dropColumn: standardDropColumn,
  modifyColumn: standardModifyColumn,
  dropTable: standardDropTable,
  // A new table's schema and the sequences its defaults draw from, both `IF NOT EXISTS`, so a migration into a
  // database that has them already runs unchanged (R9). Measured on PostgreSQL 19.0: without them a 51-table
  // migration replayed into an empty database stopped at `relation "app.x_seq" does not exist`.
  prerequisites: (container, columns) => [
    ...(container === undefined ? [] : [`CREATE SCHEMA IF NOT EXISTS ${container};`]),
    ...columns.flatMap((col) => {
      const sequence = sequenceOf(col);
      return sequence === undefined ? [] : [`CREATE SEQUENCE IF NOT EXISTS ${sequence}${sequenceOptions(col)};`];
    }),
  ],
  // A sequence its column owned (a serial's) is given back to it once the column exists, so dropping the column or
  // its table drops the sequence again, as it did where the migration was read.
  ownership: (table, columns) =>
    columns.flatMap(([col, column]) => {
      const sequence = sequenceOf(col);
      return sequence !== undefined && col.targetSequence?.ownedByColumn === true
        ? [`ALTER SEQUENCE ${sequence} OWNED BY ${table}.${column};`]
        : [];
    }),
  reasons: [],
};
