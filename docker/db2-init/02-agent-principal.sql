-- The agent's least-privilege user for the Db2 LUW provider's read-only profile, run by 02-agent-principal.sh after
-- the object fixture. AGENT_RO is an operating-system user of the container, as every Db2 LUW user is; the script
-- creates it. It gets CONNECT and SELECT on two fixture tables, and nothing else.
--
-- The agent's check before each statement refuses a user whose groups, roles or PUBLIC hold anything that writes or
-- runs outside the read (docs/providers/db2.md, "The agent user"). A fresh 12.1 database gives PUBLIC exactly these,
-- so they are revoked here, from every user of this database: UPDATE on the statistics views, CREATEIN and DROPIN on
-- the public alias schema SYSPUBLIC, CREATEIN on SYSTOOLS, EXECUTE on the SYSPROC procedures that write a server file,
-- reach another server or schedule work, and EXECUTE on the DBMS_JOB module. Grant one back to a user that needs it.
GRANT CONNECT ON DATABASE TO USER AGENT_RO;
GRANT SELECT ON APP.ORDERS TO USER AGENT_RO;
GRANT SELECT ON APP.CUSTOMERS TO USER AGENT_RO;
REVOKE UPDATE ON SYSSTAT.COLDIST FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.COLDISTPARTITIONSTATS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.COLGROUPDIST FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.COLGROUPDISTCOUNTS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.COLGROUPPARTITIONSTATS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.COLGROUPS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.COLPARTITIONSTATS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.COLUMNS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.DATAPARTITIONS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.FUNCTIONS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.INDEXES FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.INDEXPARTITIONS FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.ROUTINES FROM PUBLIC;
REVOKE UPDATE ON SYSSTAT.TABLES FROM PUBLIC;
REVOKE CREATEIN, DROPIN ON SCHEMA SYSPUBLIC FROM PUBLIC;
REVOKE CREATEIN ON SCHEMA SYSTOOLS FROM PUBLIC;
REVOKE EXECUTE ON SPECIFIC PROCEDURE SYSPROC.ADMIN_CMD FROM PUBLIC RESTRICT;
REVOKE EXECUTE ON SPECIFIC PROCEDURE SYSPROC.ADMIN_TASK_ADD FROM PUBLIC RESTRICT;
REVOKE EXECUTE ON SPECIFIC PROCEDURE SYSPROC.ADMIN_TASK_UPDATE FROM PUBLIC RESTRICT;
REVOKE EXECUTE ON SPECIFIC PROCEDURE SYSPROC.DB2LOAD FROM PUBLIC RESTRICT;
REVOKE EXECUTE ON SPECIFIC PROCEDURE SYSPROC.REMOTE_QUERY FROM PUBLIC RESTRICT;
REVOKE EXECUTE ON SPECIFIC PROCEDURE SYSPROC.SNAP_WRITE_FILE FROM PUBLIC RESTRICT;
REVOKE EXECUTE ON SPECIFIC PROCEDURE SYSPROC.SYSTS_ADMIN_CMD FROM PUBLIC RESTRICT;
REVOKE EXECUTE ON MODULE SYSIBMADM.DBMS_JOB FROM PUBLIC;
