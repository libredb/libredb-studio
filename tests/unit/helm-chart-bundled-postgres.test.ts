// @requires helm
/**
 * The bundled PostgreSQL subchart (postgresql.enabled=true) serves plain TCP unless
 * postgresql.tls.enabled is set, while Studio's storage pool turns TLS on for any
 * non-local host whose STORAGE_POSTGRES_URL names no sslmode (src/lib/pg-ssl.ts).
 * The chart therefore writes sslmode=disable into the URL it builds for the bundled
 * database while the subchart's TLS is off, and leaves the secure default alone when
 * it is on. Without that, sign-in answered 500 "server does not support SSL".
 * Exercises the real `helm template` output, then hands the rendered URL to the
 * same pgSslConfig the storage provider uses.
 */
import { describe, expect, test } from "bun:test";
import { join } from "node:path";
import { parseAllDocuments } from "yaml";
import { pgSslConfig } from "@/lib/pg-ssl";
import { howItFailed } from "../helpers/spawn-outcome";

const CHART_DIR = join(import.meta.dir, "../../charts/libredb-studio");

interface EnvVar {
  name: string;
  value?: string;
  valueFrom?: { secretKeyRef?: { name: string; key: string } };
}

interface RenderedDeployment {
  kind: string;
  spec: { template: { spec: { containers: Array<{ env: EnvVar[] }> } } };
}

function renderEnv(extraArgs: string[] = []): EnvVar[] {
  const run = Bun.spawnSync(["helm", "template", "release-under-test", CHART_DIR, ...extraArgs], {
    stdout: "pipe",
    stderr: "pipe",
  });
  if (run.exitCode !== 0) {
    throw new Error(`helm template ${howItFailed(run)}: ${run.stderr.toString()}`);
  }
  const docs = parseAllDocuments(run.stdout.toString()).map((doc) => doc.toJSON() as RenderedDeployment);
  const deployment = docs.find((doc) => doc?.kind === "Deployment");
  if (!deployment) throw new Error("no Deployment manifest found in rendered chart output");
  return deployment.spec.template.spec.containers[0].env;
}

function storageUrl(env: EnvVar[]): EnvVar | undefined {
  return env.find((entry) => entry.name === "STORAGE_POSTGRES_URL");
}

/** The URL as the pod sees it once Kubernetes expands $(POSTGRES_PASSWORD). */
function expanded(url: string): string {
  return url.replace("$(POSTGRES_PASSWORD)", "not-a-real-password");
}

describe("charts/libredb-studio STORAGE_POSTGRES_URL for the bundled PostgreSQL", () => {
  test("the subchart's default (TLS off) gets sslmode=disable, so the storage pool connects without TLS", () => {
    const url = storageUrl(renderEnv(["--set", "postgresql.enabled=true"]))?.value;
    expect(url).toBe(
      "postgresql://libredb:$(POSTGRES_PASSWORD)@release-under-test-postgresql:5432/libredb_storage?sslmode=disable",
    );
    expect(pgSslConfig(expanded(url ?? ""))).toBe(false);
  });

  test("postgresql.tls.enabled=false explicitly is the same as the default", () => {
    const url = storageUrl(
      renderEnv(["--set", "postgresql.enabled=true", "--set", "postgresql.tls.enabled=false"]),
    )?.value;
    expect(url).toEndWith("/libredb_storage?sslmode=disable");
  });

  test("postgresql.tls.enabled=true keeps no sslmode, so Studio's TLS default applies", () => {
    const url = storageUrl(
      renderEnv([
        "--set",
        "postgresql.enabled=true",
        "--set",
        "postgresql.tls.enabled=true",
        "--set",
        "postgresql.tls.autoGenerated=true",
      ]),
    )?.value;
    expect(url).toBe("postgresql://libredb:$(POSTGRES_PASSWORD)@release-under-test-postgresql:5432/libredb_storage");
    expect(pgSslConfig(expanded(url ?? ""))).toEqual({ rejectUnauthorized: false });
  });

  test("an external secrets.storagePostgresUrl still comes from the Secret, untouched", () => {
    const env = renderEnv([
      "--set",
      "config.storageProvider=postgres",
      "--set",
      "secrets.storagePostgresUrl=postgresql://user:pass@db.example.com:5432/libredb",
    ]);
    const entry = storageUrl(env);
    expect(entry?.value).toBeUndefined();
    expect(entry?.valueFrom?.secretKeyRef?.key).toBe("storage-postgres-url");
    expect(env.find((e) => e.name === "POSTGRES_PASSWORD")).toBeUndefined();
  });

  test("an existingSecret still supplies the URL, untouched", () => {
    const entry = storageUrl(
      renderEnv(["--set", "config.storageProvider=postgres", "--set", "secrets.existingSecret=my-studio-secret"]),
    );
    expect(entry?.value).toBeUndefined();
    expect(entry?.valueFrom?.secretKeyRef?.name).toBe("my-studio-secret");
  });
});
